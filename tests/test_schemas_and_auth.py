def test_password_hashes_are_django_compatible():
    encoded = make_password("s3cret", iterations=1000)
    assert encoded.startswith("pbkdf2_sha256$1000$")
    assert check_password("s3cret", encoded)
    assert not check_password("wrong", encoded)
    assert needs_rehash(encoded)
    # Generated by Django 5.2 (django.contrib.auth.hashers.make_password("django-password")):
    django_hash = "pbkdf2_sha256$1000000$3oVOwZR128kdn60p1RyQT4$aHc9glllE1p2SH1MS6h8CWWDlwHlbhZ0eosvBLoNWe0="
    assert check_password("django-password", django_hash)
    assert not check_password("anything", "!")


