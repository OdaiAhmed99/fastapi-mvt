async def test_lockout_after_repeated_failures(db):
    auth = Auth(Account, secret_key=SECRET, max_failed_logins=3, lockout_minutes=15)
    app = FastAPI()
    db.init_app(app)
    app.include_router(auth.router)
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://t") as c:
        await register_and_login(c)
        wrong = {"email": "ada@example.com", "password": "wrong-password"}
        assert [(await c.post("/auth/login", json=wrong)).status_code for _ in range(3)] == [401, 401, 401]
        # Locked now: even the right password is refused, and the counter was committed despite the 401s.
        locked = await c.post("/auth/login", json={"email": "ada@example.com", "password": "correct-horse"})
        assert locked.status_code == 429 and "Retry-After" in locked.headers
        account = await Account.objects.get(email="ada@example.com")
        assert account.locked_until is not None

        await Account.objects.filter(id=account.id).update(locked_until=None)
        ok = await c.post("/auth/login", json={"email": "ada@example.com", "password": "correct-horse"})
        assert ok.status_code == 200


async def test_password_reset_flow(db):
    sent: list[str] = []

    async def send(user, token):
        sent.append(token)

    auth = Auth(Account, secret_key=SECRET, send_password_reset=send)
    app = FastAPI()
    db.init_app(app)
    app.include_router(auth.router)
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://t") as c:
        tokens = await register_and_login(c)
        unknown = await c.post("/auth/password-reset", json={"email": "nobody@example.com"})
        known = await c.post("/auth/password-reset", json={"email": "ada@example.com"})
        assert unknown.status_code == known.status_code == 202
        assert unknown.json() == known.json()  # doesn't reveal which emails exist
        assert len(sent) == 1

        confirm = {"token": sent[0], "new_password": "brand-new-password"}
        assert (await c.post("/auth/password-reset/confirm", json=confirm)).status_code == 204
        assert (await c.post("/auth/password-reset/confirm", json=confirm)).status_code == 400  # single use
        assert (await c.get("/auth/me", headers=bearer(tokens["access_token"]))).status_code == 401  # old tokens revoked
        await register_and_login_existing(c, "ada@example.com", "brand-new-password")
        bad = {"token": "not-a-token", "new_password": "whatever-123"}
        assert (await c.post("/auth/password-reset/confirm", json=bad)).status_code == 400


