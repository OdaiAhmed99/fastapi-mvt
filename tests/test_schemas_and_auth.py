def bearer(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


async def register_and_login(c, email="Ada@Example.com", password="correct-horse"):
    r = await c.post("/auth/register", json={"email": email, "password": password})
    assert r.status_code == 201, r.text
    r = await c.post("/auth/login", json={"email": email, "password": password})
    assert r.status_code == 200, r.text
    return r.json()


async def test_register_login_me(auth_client):
    tokens = await register_and_login(auth_client)
    me = await auth_client.get("/auth/me", headers=bearer(tokens["access_token"]))
    assert me.status_code == 200
    body = me.json()
    assert body["email"] == "ada@example.com"  # normalised
    assert "password" not in body and "token_version" not in body
    account = await Account.objects.get(email="ada@example.com")
    assert account.password.startswith("pbkdf2_sha256$") and account.last_login is not None


async def test_duplicate_and_invalid_registration(auth_client):
    await register_and_login(auth_client)
