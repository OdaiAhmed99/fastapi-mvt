def test_model_schema_modes():
    read = model_schema(Post)
    create = model_schema(Post, "create")
    update = model_schema(Post, "update")

    assert {"id", "created_at", "updated_at", "title"} <= set(read.model_fields)
    assert "id" not in create.model_fields and "created_at" not in create.model_fields
    assert create.model_fields["title"].is_required()
    assert not create.model_fields["views"].is_required()
    assert create.model_fields["views"].default == 0
    assert not any(f.is_required() for f in update.model_fields.values())

    with pytest.raises(ValidationError, match="200"):
        create(title="x" * 201, author_id=1)
    # Regression: timestamps must be parsed into datetimes, not passed through as strings.
    parsed = read(**{**dict.fromkeys(read.model_fields), "id": 1, "title": "t", "views": 0, "author_id": 1,
                     "created_at": "2026-01-01T10:00:00+00:00", "updated_at": "2026-01-01T10:00:00Z"})
    assert parsed.created_at.year == 2026 and parsed.created_at.tzinfo is not None


